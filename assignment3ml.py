class gen1(nn.Module):
    def __init__(self, noise_dim=100, num_classes=12):
        super().__init__()
        self.embed = nn.Embedding(num_classes, 32)
        self.a = nn.Linear(noise_dim + 32, 512)
        self.b = nn.Linear(512, 50 * 32 * 32)

    def forward(self, z, labels):
        emb = self.embed(labels)
        x = torch.cat([z, emb], dim=1)
        x = torch.relu(self.a(x))
        x = torch.tanh(self.b(x))
        return x.view(-1, 50, 32, 32)


class dis1(nn.Module):
    def __init__(self, num_classes=12):
        super().__init__()
        self.embed = nn.Embedding(num_classes, 50 * 32 * 32)
        self.a = nn.Conv3d(1, 6, 3, padding=1)
        self.b = nn.MaxPool3d(2)
        self.c = nn.Linear(6 * 25 * 16 * 16, 1)

    def forward(self, x, labels):
        label_map = self.embed(labels).view(-1, 50, 32, 32)
        x = x + 0.1 * label_map
        x = x.unsqueeze(1)
        x = self.b(torch.relu(self.a(x)))
        x = x.view(x.size(0), -1)
        return self.c(x)


