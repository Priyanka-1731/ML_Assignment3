import numpy as np

def dann_lambda(epoch, total_epochs):
    p = epoch / total_epochs
    return float(2.0 / (1.0 + np.exp(-10.0 * p)) - 1.0)

class gr(torch.autograd.Function):
    @staticmethod
    def forward(ctx, x, temp1):
        ctx.temp1 = temp1
        return x.view_as(x)

    @staticmethod
    def backward(ctx, g):
        return -ctx.temp1 * g, None


class mm2(nn.Module):
    def __init__(self):
        super().__init__()

        self.a = nn.Conv3d(1, 6, 3, padding=1)
        self.b = nn.MaxPool3d(2)

        self.c = nn.Conv3d(6, 12, 3, padding=1)
        self.d = nn.MaxPool3d(2)

        self.e = nn.Linear(12 * 12 * 8 * 8, 64)

        self.f = nn.Linear(64, 12)
        self.g = nn.Linear(64, 16)

    def forward(self, x, temp1=0.2):
        x = x.unsqueeze(1)

        x = self.b(torch.relu(self.a(x)))
        x = self.d(torch.relu(self.c(x)))

        x = x.view(x.size(0), -1)

        x = torch.relu(self.e(x))

        out1 = self.f(x)

        temp2 = gr.apply(x, temp1)
        out2 = self.g(temp2)

        return out1, out2


